"""Minimal OpenAI-compatible chat completion client.

The project intentionally avoids depending on the OpenAI SDK in phase 1 so the
file pipeline can run with only the standard library plus pydantic.
"""

from __future__ import annotations

import json
import urllib.error
import urllib.request
from collections.abc import Iterator
from dataclasses import dataclass
from typing import Any

import json_repair
from pydantic import BaseModel

from law_agent.config import LLMConfig
from law_agent.llm.structured_stream import receive_json_response
from law_agent.llm.usage import UsageRequest


@dataclass(frozen=True)
class ChatMessage:
    role: str
    content: str | None
    tool_calls: list[dict[str, Any]] | None = None
    tool_call_id: str | None = None
    reasoning_content: str | None = None

    def to_dict(self) -> dict[str, Any]:
        return {key: value for key, value in self.__dict__.items() if value is not None or key == "content"}


class OpenAICompatibleClient:
    """Small client for `/chat/completions` providers."""

    def __init__(self, config: LLMConfig) -> None:
        self.config = config

    def stream_text(self, messages: list[ChatMessage], *, model: str | None = None,
                    tools: list[dict] | None = None) -> Iterator[str]:
        """Yield content deltas from an OpenAI-compatible SSE completion."""
        if not self.config.api_key:
            raise RuntimeError("OPENAI_COMPATIBLE_API_KEY is not configured")
        payload: dict[str, Any] = {
            "model": model or self.config.model,
            "messages": [message.to_dict() for message in messages],
            "stream": True,
            "stream_options": {"include_usage": True},
        }
        if tools is not None:
            payload.update(tools=tools, tool_choice="none")
        if self.config.reasoning_effort != "none":
            payload["thinking"] = {"type": "enabled"}
            payload["reasoning_effort"] = self.config.reasoning_effort
        else:
            payload["thinking"] = {"type": "disabled"}
            payload["temperature"] = 0
        request = urllib.request.Request(
            f"{self.config.base_url}/chat/completions",
            data=json.dumps(payload, ensure_ascii=False).encode("utf-8"),
            headers={"Authorization": f"Bearer {self.config.api_key}", "Content-Type": "application/json"},
            method="POST",
        )
        accounting = UsageRequest(payload)
        status, error = "failed", None
        try:
            with urllib.request.urlopen(request, timeout=self.config.timeout_seconds) as response:
                for raw_line in response:
                    line = raw_line.decode("utf-8").strip()
                    if not line.startswith("data:"):
                        continue
                    data = line[5:].strip()
                    if data == "[DONE]":
                        status = "completed"
                        return
                    event = json.loads(data)
                    accounting.observe(event)
                    if event.get("error"):
                        raise RuntimeError("LLM stream returned an error")
                    for choice in event.get("choices", []):
                        delta = choice.get("delta", {})
                        if delta.get("tool_calls"):
                            raise RuntimeError("LLM answer stream returned an unexpected tool call")
                        content = delta.get("content")
                        if content:
                            accounting.token()
                            yield content
                        reason = choice.get("finish_reason")
                        if reason and reason != "stop":
                            raise RuntimeError(f"LLM stream ended with {reason}")
                raise RuntimeError("LLM stream interrupted before completion")
        except urllib.error.HTTPError as exc:
            error = type(exc).__name__
            raise RuntimeError(f"LLM streaming request failed with HTTP {exc.code}") from exc
        except GeneratorExit:
            status, error = "cancelled", "GeneratorExit"
            raise
        except Exception as exc:
            error = type(exc).__name__
            raise
        finally:
            accounting.finish(status, error)

    def chat_json(
        self,
        messages: list[ChatMessage],
        *,
        output_model: type[BaseModel] | None = None,
        tool_name: str = "structured_output",
        model: str | None = None,
        structured_output_mode: str | None = None,
        stream: bool = False,
    ) -> dict:
        """Return a JSON object generated by the model.

        ``structured_output_mode`` overrides ``self.config.structured_output_mode``
        for this call only — used by nodes that need a looser mode (e.g.
        result_generation emits markdown inside string fields and should not
        be constrained by strict_tool's schema requirements).
        """

        if not self.config.api_key:
            raise RuntimeError("OPENAI_COMPATIBLE_API_KEY is not configured")

        mode = structured_output_mode or self.config.structured_output_mode
        if mode == "strict_tool" and output_model is not None:
            if stream:
                raise ValueError("Internal JSON streaming requires json_object output")
            return self._chat_strict_tool(messages, output_model, tool_name, model=model)

        payload = {
            "model": model or self.config.model,
            "messages": [message.to_dict() for message in messages],
            "temperature": 0,
            "response_format": {"type": "json_object"},
        }
        if self.config.reasoning_effort != "none":
            payload.pop("temperature")
            payload["thinking"] = {"type": "enabled"}
            payload["reasoning_effort"] = self.config.reasoning_effort
        else:
            payload["thinking"] = {"type": "disabled"}
        if stream:
            return receive_json_response(payload, self.config)
        data = self._post_chat(payload, self.config.base_url)
        choice = data["choices"][0]
        if choice.get("finish_reason") == "length":
            # 截断是确定性的：用同一 payload 重试不可能成功，立即以独立原因失败
            raise RuntimeError(
                "LLM response truncated by max output tokens (finish_reason=length); "
                "payload must be shortened or max_tokens raised"
            )
        content = choice["message"]["content"]
        try:
            return json.loads(content)
        except json.JSONDecodeError:
            # 宽松修复常见的小破损（尾逗号/未闭合）；修复后再失败才视为真实错误
            import json_repair

            repaired = json_repair.loads(content)
            if isinstance(repaired, (dict, list)):
                return repaired
            raise

    def chat_tools(self, messages: list[ChatMessage], *, tools: list[dict], model: str | None = None,
                   on_text=None) -> dict:
        if not self.config.api_key:
            raise RuntimeError("OPENAI_COMPATIBLE_API_KEY is not configured")
        payload = {"model": model or self.config.model, "messages": [m.to_dict() for m in messages],
                   "tools": tools, "tool_choice": "auto"}
        if self.config.reasoning_effort != "none":
            payload.update(thinking={"type": "enabled"}, reasoning_effort=self.config.reasoning_effort)
        else:
            payload.update(thinking={"type": "disabled"}, temperature=0)
        if on_text is not None:
            return self._stream_tools(payload, on_text)
        choice = self._post_chat(payload, self._tool_base_url(tools))["choices"][0]
        if choice.get("finish_reason") not in {"tool_calls", "stop"}:
            raise RuntimeError(f"LLM tool response ended with {choice.get('finish_reason')}")
        return choice["message"]

    def _tool_base_url(self, tools: list[dict]) -> str:
        strict = [tool.get("function", {}).get("strict") is True for tool in tools]
        if any(strict):
            if not all(strict):
                raise ValueError("strict工具调用要求所有function均启用strict")
            return self.config.beta_base_url
        return self.config.base_url

    def _stream_tools(self, payload: dict, on_text) -> dict:
        payload.update(stream=True, stream_options={"include_usage": True})
        request = urllib.request.Request(
            f"{self._tool_base_url(payload['tools'])}/chat/completions",
            data=json.dumps(payload, ensure_ascii=False).encode("utf-8"),
            headers={"Authorization": f"Bearer {self.config.api_key}", "Content-Type": "application/json"},
            method="POST",
        )
        accounting = UsageRequest(payload)
        status, error, finish_reason = "failed", None, None
        content, reasoning, calls = [], [], {}
        try:
            with urllib.request.urlopen(request, timeout=self.config.timeout_seconds) as response:
                for raw_line in response:
                    line = raw_line.decode("utf-8").strip()
                    if not line.startswith("data:"):
                        continue
                    data = line[5:].strip()
                    if data == "[DONE]":
                        if finish_reason not in {"tool_calls", "stop"}:
                            raise RuntimeError("LLM tool stream interrupted before completion")
                        message = {"role": "assistant", "content": "".join(content) or None}
                        if reasoning or payload.get("thinking", {}).get("type") == "enabled":
                            message["reasoning_content"] = "".join(reasoning)
                        if calls:
                            message["tool_calls"] = [calls[index] for index in sorted(calls)]
                        elif finish_reason == "tool_calls":
                            raise RuntimeError("LLM tool stream ended without tool calls")
                        status = "completed"
                        return message
                    event = json.loads(data)
                    accounting.observe(event)
                    if event.get("error"):
                        raise RuntimeError("LLM tool stream returned an error")
                    for choice in event.get("choices", []):
                        delta = choice.get("delta", {})
                        if delta.get("reasoning_content"):
                            reasoning.append(delta["reasoning_content"])
                        for part in delta.get("tool_calls") or []:
                            call = calls.setdefault(part["index"], {"id": "", "type": "function",
                                "function": {"name": "", "arguments": ""}})
                            if part.get("id"):
                                call["id"] += part["id"]
                            if part.get("type"):
                                call["type"] = part["type"]
                            function = part.get("function") or {}
                            for key in ("name", "arguments"):
                                if function.get(key):
                                    call["function"][key] += function[key]
                        if delta.get("content"):
                            content.append(delta["content"])
                            accounting.token()
                            on_text(delta["content"])
                        if choice.get("finish_reason"):
                            finish_reason = choice["finish_reason"]
                            if finish_reason not in {"tool_calls", "stop"}:
                                raise RuntimeError(f"LLM tool stream ended with {finish_reason}")
                raise RuntimeError("LLM tool stream interrupted before completion")
        except urllib.error.HTTPError as exc:
            error = type(exc).__name__
            raise RuntimeError(f"LLM tool stream failed with HTTP {exc.code}") from exc
        except Exception as exc:
            error = type(exc).__name__
            raise
        finally:
            accounting.finish(status, error)

    def _chat_strict_tool(
        self,
        messages: list[ChatMessage],
        output_model: type[BaseModel],
        tool_name: str,
        *,
        model: str | None = None,
    ) -> dict:
        schema = _schema_for_strict_tool(output_model)
        payload: dict[str, Any] = {
            "model": model or self.config.model,
            "messages": [message.to_dict() for message in messages],
            "temperature": 0,
            "tools": [
                {
                    "type": "function",
                    "function": {
                        "name": tool_name,
                        "description": f"Return a validated {output_model.__name__} JSON object.",
                        "parameters": schema,
                        "strict": True,
                    },
                }
            ],
            "tool_choice": {
                "type": "function",
                "function": {"name": tool_name},
            },
        }
        if self.config.reasoning_effort != "none":
            raise RuntimeError(
                "DeepSeek thinking mode does not support forced named tool_choice; "
                "use json_object output or reasoning_effort=none"
            )
        payload["thinking"] = {"type": "disabled"}
        data = self._post_chat(payload, self.config.beta_base_url)

        message = data["choices"][0]["message"]
        tool_calls = message.get("tool_calls") or []
        if not tool_calls:
            raise RuntimeError("LLM strict tool response did not include tool_calls")
        arguments = tool_calls[0].get("function", {}).get("arguments")
        if not isinstance(arguments, str):
            raise RuntimeError(  # noqa: TRY004
                "LLM strict tool response did not include JSON arguments"
            )
        return _loads_tool_arguments(arguments)

    def _post_chat(self, payload: dict[str, Any], base_url: str) -> dict:
        body = json.dumps(payload, ensure_ascii=False).encode("utf-8")
        request = urllib.request.Request(
            f"{base_url}/chat/completions",
            data=body,
            headers={
                "Authorization": f"Bearer {self.config.api_key}",
                "Content-Type": "application/json",
            },
            method="POST",
        )
        accounting = UsageRequest(payload)
        status, error = "failed", None
        try:
            with urllib.request.urlopen(request, timeout=self.config.timeout_seconds) as response:
                data = json.loads(response.read().decode("utf-8"))
            accounting.observe(data)
            status = "completed"
        except urllib.error.HTTPError as exc:
            error = type(exc).__name__
            detail = exc.read().decode("utf-8", errors="replace")
            raise RuntimeError(f"LLM request failed with HTTP {exc.code}: {detail}") from exc
        except Exception as exc:
            error = type(exc).__name__
            raise
        finally:
            accounting.finish(status, error)

        return data


def _schema_for_strict_tool(model: type[BaseModel]) -> dict[str, Any]:
    schema = model.model_json_schema()
    definitions = schema.pop("$defs", {})
    schema = _inline_local_refs(schema, definitions)
    schema = _strip_unsupported_schema_keys(schema)
    # DeepSeek strict tool mode requires every object's `required` array to
    # list ALL of its properties — pydantic omits fields with defaults (like
    # supporting_chunk_ids: list = []) from `required`, which triggers
    # HTTP 400 "Required properties must match all properties in the object".
    _enforce_required_all_properties(schema)
    return schema


def _enforce_required_all_properties(schema: Any) -> None:
    """Recursively ensure each object's `required` lists all its properties.

    DeepSeek's strict tool mode rejects schemas where an object has a
    property not listed in `required`. pydantic only puts non-default
    fields into `required`, so we patch every object in-place.
    """

    if isinstance(schema, dict):
        if schema.get("type") == "object" and "properties" in schema:
            props = schema["properties"]
            schema["required"] = list(props.keys())
        for value in schema.values():
            _enforce_required_all_properties(value)
    elif isinstance(schema, list):
        for item in schema:
            _enforce_required_all_properties(item)


def _loads_tool_arguments(arguments: str) -> dict:
    try:
        parsed = json.loads(arguments)
    except json.JSONDecodeError:
        parsed = json_repair.loads(arguments)
    if not isinstance(parsed, dict):
        raise json.JSONDecodeError(
            "tool arguments must decode to a JSON object",
            arguments,
            0,
        )
    return parsed


def _inline_local_refs(value: Any, definitions: dict[str, Any]) -> Any:
    if isinstance(value, dict):
        ref = value.get("$ref")
        if isinstance(ref, str) and ref.startswith("#/$defs/"):
            name = ref.rsplit("/", 1)[-1]
            target = definitions.get(name)
            if target is None:
                raise RuntimeError(f"unsupported local schema reference: {ref}")
            merged = {
                **_inline_local_refs(target, definitions),
                **{k: v for k, v in value.items() if k != "$ref"},
            }
            return merged
        return {k: _inline_local_refs(v, definitions) for k, v in value.items()}
    if isinstance(value, list):
        return [_inline_local_refs(item, definitions) for item in value]
    return value


def _strip_unsupported_schema_keys(value: Any) -> Any:
    unsupported = {"title", "default", "examples"}
    if isinstance(value, dict):
        return {
            key: _strip_unsupported_schema_keys(item)
            for key, item in value.items()
            if key not in unsupported
        }
    if isinstance(value, list):
        return [_strip_unsupported_schema_keys(item) for item in value]
    return value
